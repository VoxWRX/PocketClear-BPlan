export type TranslationDictionary = (typeof TRANSLATIONS)['en'];

export function getStarterCategoriesForLanguage(
  lang: LanguageCode,
  selectedPresetIds: string[]
): NewCategory[] {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const chosen = STARTER_BUCKET_PRESETS.filter((p) => selectedPresetIds.includes(p.id));
  // Ensure at least one income bucket exists so user can immediately add Money In too
  const hasIncome = chosen.some((p) => p.type === 'income');
  const finalPresets = hasIncome
    ? chosen
    : [
        ...chosen,
        STARTER_BUCKET_PRESETS.find((p) => p.key === 'salary')!,
      ];

  return finalPresets.map((p) => ({
    name: dict.presets[p.key],
    type: p.type,
    icon: p.icon,
    color: p.color,
    monthly_budget: p.suggestedBudget,
  }));
}
